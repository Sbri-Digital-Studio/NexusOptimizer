/// <summary>Converte true/false in Visibility per overlay e toggle bound.</summary>
public sealed class BoolToVisibilityConverter : IValueConverter
{
    public object Convert(object? value, Type targetType, object? parameter, CultureInfo culture)
    {
        var visible = value is bool b && b;
        // ConverterParameter=invert: usato dai comandi che si escludono a vicenda.
        if (parameter is string flag && flag.Equals("invert", StringComparison.OrdinalIgnoreCase))
            visible = !visible;
        return visible ? Visibility.Visible : Visibility.Collapsed;
    }

    public object ConvertBack(object? value, Type targetType, object? parameter, CultureInfo culture)
        => value is Visibility v && v == Visibility.Visible;
}

/// <summary>Converte una chiave nel testo localizzato direttamente dai binding XAML.</summary>
public sealed class LocaleKeyConverter : IValueConverter
{
    public object Convert(object? value, Type targetType, object? parameter, CultureInfo culture)
        => parameter is string k ? Locale.T(k) : value?.ToString() ?? string.Empty;

    public object ConvertBack(object? value, Type targetType, object? parameter, CultureInfo culture)
        => throw new NotSupportedException();
}

/// <summary>Converte un hex "#RRGGBB" in SolidColorBrush per template di selezione accento.</summary>
public sealed class HexToBrushConverter : IValueConverter
{
    public object? Convert(object? value, Type targetType, object? parameter, CultureInfo culture)
    {
        try { return new SolidColorBrush((Color)ColorConverter.ConvertFromString(value as string ?? "#808080")); }
        catch (Exception) { return Brushes.Gray; }
    }

    public object ConvertBack(object? value, Type targetType, object? parameter, CultureInfo culture)
        => throw new NotSupportedException();
}

/// <summary>
/// Oggetto sorgente dei binding di localizzazione. Non espone testo: espone un
/// numero di revisione che cambia a ogni cambio lingua, ed e' quello a far
/// rivalutare il converter su ogni etichetta legata.
/// </summary>
public sealed class LocaleSource : System.ComponentModel.INotifyPropertyChanged
{
    public int Version { get; private set; }

    public event System.ComponentModel.PropertyChangedEventHandler? PropertyChanged;

    internal void Bump()
    {
        Version++;
        PropertyChanged?.Invoke(this, new System.ComponentModel.PropertyChangedEventArgs(nameof(Version)));
    }
}

/// <summary>Converte la chiave memorizzata nell'oggetto (r.LabelKey) nel testo localizzato.</summary>
public sealed class LocaleKeyOfConverter : IValueConverter
{
    public object Convert(object? value, Type targetType, object? parameter, CultureInfo culture)
        => value is string k ? Locale.T(k) : string.Empty;

    public object ConvertBack(object? value, Type targetType, object? parameter, CultureInfo culture)
        => throw new NotSupportedException();
}

/// La chiave mancante ritorna l'identificatore stesso: mai testo segnaposto silenzioso in UI.
/// Dizionario inglese separato in <see cref="Locale"/> file parziale Locale.En.cs.
/// </summary>
public static partial class Locale
{
    /// <summary>Raised dopo un cambio lingua: le viste rialzano le proprietà localizzate.</summary>
    public static event Action? Changed;

    /// <summary>
    /// Sorgente osservabile a cui sono legati i testi statici dello XAML. Cambiando
    /// lingua incrementa <see cref="LocaleSource.Version"/>: WPF rivaluta i binding
    /// e ogni etichetta si riscrive subito, senza dover uscire e rientrare nella pagina.
    /// </summary>
    public static LocaleSource Live { get; } = new();

    // I dizionari sono dichiarati più avanti nel tipo: il fallback lazy evita
    // che un converter XAML venga eseguito durante l'inizializzazione statica.
    private static Dictionary<string, string>? _cur;
    public static string Lang { get; private set; } = "it";

    public static void Set(string lang)
    {
        _cur = lang == "en" ? En : It;
        Lang = ReferenceEquals(_cur, En) ? "en" : "it";
        ApplyCulture();
        Live.Bump();
        Changed?.Invoke();
    }

    /// <summary>Cultura numerica e di data corrispondente alla lingua scelta.</summary>
    public static CultureInfo Culture =>
        Lang == "en" ? CultureInfo.GetCultureInfo("en-US") : CultureInfo.GetCultureInfo("it-IT");

    /// <summary>
    /// La lingua dell'interfaccia decide anche il formato di numeri e date, in
    /// tutto il processo: un PC in inglese con Nexus in italiano continua a
    /// mostrare "2,3 GB", e viceversa. Il formato non dipende dal sistema.
    /// </summary>
    private static void ApplyCulture()
    {
        var culture = Culture;
        CultureInfo.DefaultThreadCurrentCulture = culture;
        CultureInfo.DefaultThreadCurrentUICulture = culture;
        CultureInfo.CurrentCulture = culture;
        CultureInfo.CurrentUICulture = culture;
    }

    public static string T(string key)
    {
        var current = _cur ?? It;
        return current.TryGetValue(key, out var value) ? value : key;
    }

    /// <summary>
    /// Testo localizzato con segnaposto {0}, {1}... risolti. Un formato malformato
    /// non deve mai far crollare l'interfaccia: in quel caso si mostra il testo grezzo.
    /// </summary>
    public static string F(string key, IReadOnlyList<string> args)
    {
        var text = T(key);
        if (args is null || args.Count == 0) return text;
        try { return string.Format(CultureInfo.CurrentCulture, text, [.. args]); }
        catch (FormatException) { return text; }
    }

    /// <summary>
    /// Chiavi di un dizionario. Serve al gate di test che verifica la parita' fra
    /// italiano e inglese: una chiave presente in una sola lingua produce testo
    /// misto nell'interfaccia, ed e' esattamente cio' che non deve accadere.
    /// </summary>
    internal static IReadOnlyCollection<string> KeysOf(string lang)
        => (lang == "en" ? En : It).Keys;

    /// <summary>Dizionario completo: il gate di test confronta anche i segnaposto.</summary>
    internal static IReadOnlyDictionary<string, string> DictionaryOf(string lang)
        => lang == "en" ? En : It;

    /// <summary>
    /// Numero piu' parola concordata, con le due forme prese dal dizionario:
    /// "1 voce disattivata" / "3 voci disattivate". Ogni lingua sceglie le proprie
    /// forme, senza che il codice debba conoscere le regole di plurale.
    /// </summary>
    public static string P(int count, string singularKey, string pluralKey)
        => Formatter.Pluralize(count, T(singularKey), T(pluralKey));

